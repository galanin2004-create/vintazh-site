import meta from "@/data/crm-meta.json";

/**
 * Подключена ли касса — снимок на момент сборки.
 *
 * Значение приходит из CRM (`GET /api/availability`, поле `pay`) и
 * записывается в data/crm-meta.json скриптом scripts/pull-crm-items.mjs.
 * Нужен именно снимок, а не запрос из браузера: от него зависят заголовки
 * и подводки статических страниц, и если решать это на клиенте, текст
 * будет меняться на глазах у посетителя.
 *
 * Пока касса не подключена, сайт говорит о бесплатной брони, а не об
 * оплате картой: обещать то, чего нет, хуже, чем описать как есть.
 * Включится касса — следующая сборка (после «Опубликовать» в приёмке или
 * ночная) сама переведёт тексты на оплату.
 */
export const payEnabled: boolean = meta.pay === true;
