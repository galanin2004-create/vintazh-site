/** Подставляет реквизиты. Пустое поле — null: страница выделит пропуск. */
export function fillTokens(text: string): (string | { missing: string })[] {
  const out: (string | { missing: string })[] = [];
  const re = /\{\{(name|inn|ogrnip|address|email|phone)\}\}/g;
  let last = 0;
  for (const m of text.matchAll(re)) {
    out.push(text.slice(last, m.index));
    const key = m[1] as keyof typeof seller;
    out.push(seller[key] ? seller[key] : { missing: key });
    last = (m.index ?? 0) + m[0].length;
  }
  out.push(text.slice(last));
  return out.filter((p) => p !== "");
}
